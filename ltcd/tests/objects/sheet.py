import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engine"))
import cairo, objects as O, ink, character as C
W, H = 2400, 1600
surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W, H); cr = cairo.Context(surf)
cr.set_source_rgb(*ink.PAPER); cr.paint()
cr.save(); cr.translate(-100, -200); cr.scale(0.8, 0.8)
O.draw_tub(cr, 450, 1478, 1.0, 1.0, "back"); O.draw_tub(cr, 450, 1478, 1.0, 1.0, "front", ripple=0.3)
O.draw_bomb(cr, 1150, 1478, 1.0, 1.0, light=1.0)
O.draw_cone(cr, 1600, 1250, 1.0)
O.draw_fish(cr, 1600, 1450, 1.0, 0.2, 1.0)
st = dict(O.DINO); st.update(x=2300, mouth=0.0, arms=1.0, smile=0.6, blush=0.6)
O.draw_dino(cr, st, 1.0)
cr.restore()
cr.save(); cr.translate(1350, -200); cr.scale(0.5, 0.5)
st2 = dict(O.DINO); st2.update(x=900, mouth=1.0, lean=0.6, hearts=1.0, eyes="happy")
O.draw_dino(cr, st2, 1.0)
O.draw_build_cloud(cr, 1900, 1100, 1.3, 1.0, 2.0)
cr.restore()
cr.save(); cr.translate(1200, 900); cr.scale(0.5, 0.5)
p = C.pose("stand", "neutral", soot=1.0, frizz=1.0); C.draw_guy(cr, 1.0, C.constrain(dict(p)), 0.0)
O.draw_noodle_hat(cr, p)
cr.restore()
surf.write_to_png("sheet.png"); print("ok")
